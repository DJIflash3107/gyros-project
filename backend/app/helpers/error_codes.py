import random
import string


def generate_error_code(prefix: str = "ERR-") -> str:
    """Generate a unique 5-digit traceable error code like ERR-67787."""
    code = "".join(random.choices(string.digits, k=5))
    return f"{prefix}{code}" if prefix else code


